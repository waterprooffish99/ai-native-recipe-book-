"""ChefAIService (T131, T132, T133)

Phase 9: Conversational Chef AI — Halal filter, chat loop, and fridge logic matching.

Architecture:
  - Halal filter: deterministic Python blocklist-first (T131), applied BOTH to
    incoming user query AND outgoing AI response (double-guard pattern).
  - Chat (T132): Sends conversation history to gpt-4o-mini, persists session to
    Neon Postgres chef_ai_sessions table, returns ChefAIChatResponse.
  - Fridge Logic (T133): Fetches all active recipes from DB, compares ingredient
    name overlap against user inventory, returns ranked RecipeSuggestion list.

Design constraints:
  - NO frontend imports.
  - NO modifications to recipe_service.py or any Phase 8 components.
  - All DB writes use the asyncpg pool (same pattern as RecipeService).
"""
